# Indicative quarterly expiry used for the F&O catalog rows.
_QUARTERLY_EXPIRY = date(2026, 9, 24)


@dataclass(frozen=True)
class CatalogRow:
    symbol: str
    name: str
    exchange: str
    instrument_type: str
    segment: str
    expiry: date | None
    strike_price: float | None
    option_type: str | None
    lot_size: int
    tick_size: float


def _eq(symbol: str, name: str, exchange: str = "NSE") -> CatalogRow:
    return CatalogRow(symbol, name, exchange, "EQUITY", "EQ", None, None, None, 1, 0.05)


def _fut(symbol: str, name: str, exchange: str, lot_size: int, tick_size: float) -> CatalogRow:
    return CatalogRow(
        symbol, name, exchange, "FUTURE", "FUT", _QUARTERLY_EXPIRY, None, None, lot_size, tick_size
    )


def _opt(
    symbol: str,
    name: str,
    exchange: str,
    strike: float,
    option_type: str,
    lot_size: int,
) -> CatalogRow:
    return CatalogRow(
        symbol,
        name,
        exchange,
        "OPTION",
        "OPT",
        _QUARTERLY_EXPIRY,
        strike,
        option_type,
        lot_size,
        0.05,
    )


