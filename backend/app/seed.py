CATALOG: list[CatalogRow] = (
    NSE_EQUITY + NSE_FUTURES + NSE_OPTIONS + BSE_EQUITY + MCX_FUTURES
)


def seed_instruments(
    db: Session, exchanges: set[str] | None = None
) -> int:
    repo = InstrumentRepository(db)
    count = 0
    for row in CATALOG:
        if exchanges and row.exchange not in exchanges:
            continue
        existing = repo.get_by_natural_key(
            row.exchange,
            row.symbol,
            row.instrument_type,
            row.expiry,
            row.strike_price,
            row.option_type,
        )
        values = {
            "name": row.name,
            "instrument_type": row.instrument_type,
            "segment": row.segment,
            "expiry": row.expiry,
            "strike_price": row.strike_price,
            "option_type": row.option_type,
            "lot_size": row.lot_size,
            "tick_size": row.tick_size,
            "is_active": True,
        }
        if existing is None:
            db.add(
                Instrument(
                    symbol=row.symbol,
                    exchange=row.exchange,
                    **values,
                )
            )
        else:
            for key, value in values.items():
                setattr(existing, key, value)
        count += 1
    db.commit()
    return count


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--exchange",
        action="append",
        choices=["NSE", "BSE", "MCX"],
        help="Seed only this exchange (repeatable).",
    )
    args = parser.parse_args()
    with SessionLocal() as db:
        count = seed_instruments(db, exchanges=set(args.exchange or []))
    print(f"Seeded {count} instruments.")


if __name__ == "__main__":
    main()
