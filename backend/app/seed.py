"""Seed the reference instrument catalog.

This seeds *instrument metadata* (symbols, names, exchanges, types, lot and
tick sizes) used by the paper-trading simulation. The values are indicative
reference data for development; authoritative instrument master data will be
synchronised from a broker/exchange feed in a later phase.

Market *prices* are generated by the mock market-data provider and are never
derived from this file.

Usage:
    python -m app.seed                 # seed everything
    python -m app.seed --exchange NSE  # seed only one exchange
"""

